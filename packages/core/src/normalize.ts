import type { ColorSystem, DesignDNA } from "./types.js";
import { contrast } from "./presets.js";

/**
 * Brings a Design DNA saved by an older core version (0.1 – 0.3, before curated presets and
 * surface/text colour roles) up to the current shape, so shared links created earlier keep
 * rendering instead of crashing. Records that are already current are returned untouched.
 */
export function normalizeDesignDNA(input: DesignDNA): DesignDNA {
  const dna = input as DesignDNA & { preset?: DesignDNA["preset"]; rationale?: string };
  const c = dna.colors as Partial<ColorSystem> & Pick<ColorSystem, "neutral" | "primary">;
  const hasRoles = Boolean(c.background && c.surface && c.text && c.muted && c.border && c.mode && c.onPrimary);
  if (dna.preset && dna.rationale !== undefined && hasRoles) return dna;

  const n = c.neutral ?? [];
  const background = c.background ?? n[0] ?? "#fbfaf8";
  const text = c.text ?? n[n.length - 1] ?? "#17171a";

  const colors: ColorSystem = {
    ...(c as ColorSystem),
    mode: c.mode ?? "light",
    background,
    surface: c.surface ?? "#ffffff",
    text,
    muted: c.muted ?? n[5] ?? "#6b6b72",
    border: c.border ?? n[2] ?? "#e4e4e7",
    onPrimary: c.onPrimary ?? (contrast(c.primary, "#ffffff") >= contrast(c.primary, "#0b0b0b") ? "#ffffff" : "#0b0b0b"),
  };

  return {
    ...dna,
    colors,
    preset: dna.preset ?? {
      id: "legacy",
      name: "Classic DNA",
      inspiredBy: `Generated with @baroxy/core@${dna.coreVersion ?? "0.x"}, before curated presets`,
    },
    rationale:
      dna.rationale ??
      `This Design DNA was generated by an earlier version of Baroxy (core ${dna.coreVersion ?? "0.x"}), before the curated preset library. It is shown exactly as it was saved.`,
  };
}
